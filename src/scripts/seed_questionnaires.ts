export async function seedQuestionnaires() {
  console.log('Seeding 12 questionnaires into database...');
  for (const qData of QUESTIONNAIRES_DATA) {
    const { questions, ...qMeta } = qData;
    const questionnaire = await prisma.questionnaire.upsert({
      where: { code: qMeta.code },
      update: {
        title: qMeta.title,
        description: qMeta.description,
        category: qMeta.category,
        displayOrder: qMeta.displayOrder,
      },
      create: {
        code: qMeta.code,
        title: qMeta.title,
        description: qMeta.description,
        category: qMeta.category,
        displayOrder: qMeta.displayOrder,
      },
    });

    for (const q of questions) {
      await prisma.questionnaireQuestion.upsert({
        where: {
          questionnaireId_questionId: {
            questionnaireId: questionnaire.id,
            questionId: q.questionId,
          },
        },
        update: {
          title: q.title,
          description: (q as any).description || null,
          questionType: q.questionType,
          isRequired: q.isRequired,
          displayOrder: q.displayOrder,
          options: (q as any).options ? (q as any).options : undefined,
          conditionalParentId: (q as any).conditionalParentId || null,
          conditionalMatchValue: (q as any).conditionalMatchValue || null,
          dynamicSource: (q as any).dynamicSource || null,
        },
        create: {
          questionId: q.questionId,
          questionnaireId: questionnaire.id,
          title: q.title,
          description: (q as any).description || null,
          questionType: q.questionType,
          isRequired: q.isRequired,
          displayOrder: q.displayOrder,
          options: (q as any).options ? (q as any).options : undefined,
          conditionalParentId: (q as any).conditionalParentId || null,
          conditionalMatchValue: (q as any).conditionalMatchValue || null,
          dynamicSource: (q as any).dynamicSource || null,
        },
      });
    }
  }
  console.log('Successfully seeded all 12 questionnaires and their questions!');
}

if (require.main === module) {
  seedQuestionnaires()
    .catch(console.error)
    .finally(() => prisma.$disconnect());
}
